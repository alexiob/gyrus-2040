const tempest_web *tempest_current_web(const tempest_state *s) {
    return &tempest_webs[(s->stage - 1u) % 16u];
}
int tempest_neighbor(const tempest_web *w, int lane, int direction) {
    int n = lane + direction;
    if (n < 0)
        return w->closed ? w->lane_count - 1 : -1;
    if (n >= w->lane_count)
        return w->closed ? 0 : -1;
    return n;
}
void tempest_project(const tempest_web *w, int lane_q8, int32_t depth, int *x, int *y) {
    int max = (int)w->lane_count * 256;
    if (w->closed) {
        lane_q8 %= max;
        if (lane_q8 < 0)
            lane_q8 += max;
    } else {
        if (lane_q8 < 0)
            lane_q8 = 0;
        if (lane_q8 > max)
            lane_q8 = max;
    }
    unsigned a = (unsigned)lane_q8 / 256u, b;
    int fraction = lane_q8 % 256;
    if (a >= w->rail_count)
        a = w->rail_count - 1u;
    b = a + 1u;
    if (b >= w->rail_count)
        b = w->closed ? 0u : a;
    int px = w->rim[a].x + (w->rim[b].x - w->rim[a].x) * fraction / 256;
    int py = w->rim[a].y + (w->rim[b].y - w->rim[a].y) * fraction / 256;
    if (depth < 0)
        depth = 0;
    if (depth > TEMPEST_DEPTH)
        depth = TEMPEST_DEPTH;
    /* Integer convex perspective curve: far silhouettes remain resolvable. */
    int d = (int)(depth / 256), scale = 34 + (222 * d * d) / 65536;
    *x = 120 + px * scale / 256;
    *y = 96 + (8 * scale / 256) + py * scale / 256;
}
